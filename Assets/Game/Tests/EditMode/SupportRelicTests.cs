        [TestCase(
            "relic_saintess_silver_chalice",
            RelicEffectType.HealingIncrease,
            "Saintess's Silver Chalice",
            "Increases healing generated by the equipped character by {0}%.",
            "성녀의 은잔",
            "장착한 캐릭터가 생성하는 회복량이 {0}% 증가합니다.")]
        [TestCase(
            "relic_titans_carapace",
            RelicEffectType.ShieldAmountIncrease,
            "Titan's Carapace",
            "Increases shield amount generated by the equipped character by {0}%.",
            "거신의 갑각",
            "장착한 캐릭터가 생성하는 보호막량이 {0}% 증가합니다.")]
        public void ProductionContentRegistersSupportRelic(
            string relicId,
            RelicEffectType expectedEffectType,
            string expectedEnglishName,
            string expectedEnglishDescription,
            string expectedKoreanName,
            string expectedKoreanDescription)
        {
            DefinitionDatabase database = LoadDatabase();

            Assert.That(database.TryGetRelic(
                relicId,
                out RelicDefinition relic), Is.True);
            Assert.That(relic.Effects, Has.Count.EqualTo(1));
            RelicEffectEntry effect = relic.Effects[0];
            Assert.That(effect.EffectType, Is.EqualTo(expectedEffectType));
            Assert.That(effect.EffectRates, Is.EqualTo(ExpectedRates));
            Assert.That(effect.DescriptionValueKey, Is.EqualTo("rate"));
            Assert.That(effect.HasElementFilter, Is.False);

            Assert.That(database.TryGetRelicPresentation(
                relicId,
                out RelicPresentationDefinition presentation), Is.True);
            Assert.That(presentation.RelicId, Is.EqualTo(relicId));
            Assert.That(
                presentation.Icon == null
                    || !string.IsNullOrEmpty(
                        AssetDatabase.GetAssetPath(presentation.Icon)),
                Is.True,
                "An assigned relic icon must be a persisted Sprite asset.");

            LocalizationService localization = LoadLocalization();
            localization.SetLocale("en");
            Assert.That(localization.GetText(relic.DisplayNameKey),
                Is.EqualTo(expectedEnglishName));
            Assert.That(FormatDescription(localization, relic, 0),
                Is.EqualTo(string.Format(
                    CultureInfo.InvariantCulture,
                    expectedEnglishDescription,
                    8)));
            Assert.That(FormatDescription(localization, relic, 5),
                Is.EqualTo(string.Format(
                    CultureInfo.InvariantCulture,
                    expectedEnglishDescription,
                    18)));

            localization.SetLocale("ko");
            Assert.That(localization.GetText(relic.DisplayNameKey),
                Is.EqualTo(expectedKoreanName));
            Assert.That(FormatDescription(localization, relic, 0),
                Is.EqualTo(string.Format(
                    CultureInfo.InvariantCulture,
                    expectedKoreanDescription,
                    8)));
            Assert.That(FormatDescription(localization, relic, 5),
                Is.EqualTo(string.Format(
                    CultureInfo.InvariantCulture,
                    expectedKoreanDescription,
                    18)));
        }

        [Test]
        public void ResolverPreservesSupportSourcesAndIgnoresDuplicateSlots()
        {
            DefinitionDatabase database = LoadDatabase();
            var character = new CharacterSaveData
            {
                CharacterId = "character_a",
                Level = 1,
                Awakening = 0,
                EquippedRelicInstanceIds =
                    SaveRules.CreateEmptyRelicInstanceIdSlots()
            };
            character.EquippedRelicInstanceIds[0] = "chalice";
            character.EquippedRelicInstanceIds[1] = "carapace";
            character.EquippedRelicInstanceIds[2] = "chalice";
            var profile = new ProfileSaveData
            {
                Characters = new List<CharacterSaveData> { character },
                RelicInstances = new List<RelicInstanceSaveData>
                {
                    Instance(
                        "chalice",
                        "relic_saintess_silver_chalice",
                        0),
                    Instance(
                        "carapace",
                        "relic_titans_carapace",
                        5)
                }
            };

            RelicStatBonusSummary result = new RelicStatBonusResolver(
                database).Resolve(profile, character);

            Assert.That(result.Sources, Has.Count.EqualTo(2));
            Assert.That(result.Sources.Select(source => source.EffectType),
                Is.EqualTo(new[]
                {
                    RelicEffectType.HealingIncrease,
                    RelicEffectType.ShieldAmountIncrease
                }));
            Assert.That(result.Sources.Select(source => source.Rate),
                Is.EqualTo(new[] { 0.08d, 0.18d }));
            Assert.That(result.AttackIncreaseRateSum, Is.Zero);
            Assert.That(result.MaxHpIncreaseRateSum, Is.Zero);
            Assert.That(result.CriticalChanceIncreaseRateSum, Is.Zero);
            Assert.That(result.CriticalDamageIncreaseRateSum, Is.Zero);
        }

        [TestCase(0.08d, 1080L)]
        [TestCase(0.18d, 1180L)]
        public void HealingRelicScalesGeneratedHealingOnce(
            double rate,
            long expectedHealing)
        {
            CharacterBattleState source = Character(
                "source",
                0,
                1000,
                Source("chalice", RelicEffectType.HealingIncrease, rate));
            var party = new PartyBattleState(new[] { source });

            HealingContext context = HealingContextFactory.Build(
                new HealingContextBuildRequest(
                    source,
                    party,
                    1d,
                    false,
                    0));
            HealingResult result = HealingCalculator.Calculate(context);

            Assert.That(context.HealingIncreaseRateSum,
                Is.EqualTo(rate).Within(1e-12d));
            Assert.That(result.FinalHealing, Is.EqualTo(expectedHealing));
        }

