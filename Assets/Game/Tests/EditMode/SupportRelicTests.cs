        [Test]
        public void SupportRelicsAddWithRuntimeBuffsAndStayInOwnCategories()
        {
            CharacterBattleState source = Character(
                "source",
                0,
                1000,
                Source(
                    "chalice",
                    RelicEffectType.HealingIncrease,
                    0.18d),
                Source(
                    "carapace",
                    RelicEffectType.ShieldAmountIncrease,
                    0.18d));
            var party = new PartyBattleState(new[] { source });
            source.Effects.ApplyEffect(Effect(
                1,
                EffectModifierType.HealingIncrease,
                0.20d));
            source.Effects.ApplyEffect(Effect(
                2,
                EffectModifierType.ShieldAmountIncrease,
                0.20d));

            HealingContext healing = HealingContextFactory.Build(
                new HealingContextBuildRequest(
                    source,
                    party,
                    1d,
                    false,
                    0));
            ShieldGenerationContext shield =
                ShieldGenerationContextFactory.Build(
                    new ShieldGenerationContextBuildRequest(
                        source,
                        party,
                        1d,
                        false,
                        0));

            Assert.That(healing.HealingIncreaseRateSum,
                Is.EqualTo(0.38d).Within(1e-12d));
            Assert.That(shield.ShieldAmountIncreaseRateSum,
                Is.EqualTo(0.38d).Within(1e-12d));
            Assert.That(HealingCalculator.Calculate(healing).FinalHealing,
                Is.EqualTo(1380L));
            Assert.That(
                ShieldGenerationCalculator.Calculate(shield)
                    .FinalShieldAmount,
                Is.EqualTo(1380L));
        }

        [Test]
        public void SupportRelicsApplyOnlyToGeneratingCharacter()
        {
            CharacterBattleState first = Character("first", 0, 1000);
            CharacterBattleState second = Character(
                "second",
                1,
                1000,
                Source(
                    "chalice",
                    RelicEffectType.HealingIncrease,
                    0.18d),
                Source(
                    "carapace",
                    RelicEffectType.ShieldAmountIncrease,
                    0.18d));
            var party = new PartyBattleState(new[] { first, second });

            HealingContext firstHealing = HealingContextFactory.Build(
                new HealingContextBuildRequest(
                    first,
                    party,
                    1d,
                    false,
                    0));
            ShieldGenerationContext firstShield =
                ShieldGenerationContextFactory.Build(
                    new ShieldGenerationContextBuildRequest(
                        first,
                        party,
                        1d,
                        false,
                        0));
            HealingContext secondHealing = HealingContextFactory.Build(
                new HealingContextBuildRequest(
                    second,
                    party,
                    1d,
                    false,
                    0));

            Assert.That(firstHealing.HealingIncreaseRateSum, Is.Zero);
            Assert.That(firstShield.ShieldAmountIncreaseRateSum, Is.Zero);
            Assert.That(secondHealing.HealingIncreaseRateSum,
                Is.EqualTo(0.18d));
        }

        [Test]
        public void HealingRelicPreservesRequestedAppliedAndOverhealAmounts()
        {
            CharacterBattleState source = Character(
                "source",
                0,
                1000,
                Source(
                    "chalice",
                    RelicEffectType.HealingIncrease,
                    0.18d));
            var party = new PartyBattleState(new[] { source });
            PartyDamageApplier.Apply(party, Damage(100));
            HealingResult healing = HealingCalculator.Calculate(
                HealingContextFactory.Build(
                    new HealingContextBuildRequest(
                        source,
                        party,
                        1d,
                        false,
                        0)));

            PartyHealingApplicationResult result =
                PartyHealingApplier.Apply(party, healing);

            Assert.That(result.RequestedHealing, Is.EqualTo(1180L));
            Assert.That(result.AppliedHealing, Is.EqualTo(100L));
            Assert.That(result.OverhealAmount, Is.EqualTo(1080L));
            Assert.That(result.HpAfter, Is.EqualTo(party.MaxHp));
        }

        [Test]
        public void ShieldRelicAppliesAtCreationAndPreservesExistingShield()
        {
            CharacterBattleState source = Character(
                "source",
                0,
                1000,
                Source(
                    "carapace",
                    RelicEffectType.ShieldAmountIncrease,
                    0.18d));
            var party = new PartyBattleState(new[] { source });
            ShieldGenerationResult generation =
                ShieldGenerationCalculator.Calculate(
                    ShieldGenerationContextFactory.Build(
                        new ShieldGenerationContextBuildRequest(
                            source,
                            party,
                            1d,
                            false,
                            0)));
            ShieldGrantApplicationResult first = ShieldGrantApplier.Apply(
                party,
                generation,
                new ShieldGrantRequest(
                    1,
                    source.CharacterId,
                    1,
                    3,
                    1));
            source.Effects.ApplyEffect(Effect(
                1,
                EffectModifierType.ShieldAmountIncrease,
                0.20d));

            ShieldGenerationResult laterGeneration =
                ShieldGenerationCalculator.Calculate(
                    ShieldGenerationContextFactory.Build(
                        new ShieldGenerationContextBuildRequest(
                            source,
                            party,
                            1d,
                            false,
                            0)));
            ShieldGrantApplicationResult second = ShieldGrantApplier.Apply(
                party,
                laterGeneration,
                new ShieldGrantRequest(
                    2,
                    source.CharacterId,
                    2,
                    3,
                    2));

            Assert.That(first.RequestedShieldAmount, Is.EqualTo(1180L));
            Assert.That(first.GrantedShieldAmount, Is.EqualTo(1000L));
            Assert.That(party.Shields.ActiveShields, Has.Count.EqualTo(1));
            Assert.That(party.Shields.ActiveShields[0].CurrentAmount,
                Is.EqualTo(1000L));
            Assert.That(laterGeneration.FinalShieldAmount,
                Is.EqualTo(1380L));
            Assert.That(second.GrantedShieldAmount, Is.Zero);
            Assert.That(party.Shields.TotalShield, Is.EqualTo(party.MaxHp));
        }

        [Test]
        public void FinalMaxHpFeedsSupportBaseWithoutDoubleApplication()
        {
            CharacterDefinition definition =
                AssetDatabase.LoadAssetAtPath<CharacterDefinition>(
                    "Assets/Data/Characters/marea_bluefang.asset");
            Assert.That(definition, Is.Not.Null);
            var sources = new[]
            {
                Source(
                    "chalice",
                    RelicEffectType.HealingIncrease,
                    0.18d),
                Source(
                    "carapace",
                    RelicEffectType.ShieldAmountIncrease,
                    0.18d)
            };
            var bonuses = new RelicStatBonusSummary(
                maxHpIncreaseRateSum: 0.10d,
                attackIncreaseRateSum: 0d,
                sources: sources);
            ResolvedCharacterBuild build =
                CharacterBuildResolverFactory.CreateDefault().Resolve(
                    definition,
                    level: 100,
                    awakening: 2,
                    relicBonuses: bonuses);
            CharacterBattleState source = CharacterBattleStateFactory.Create(
                definition,
                build,
                partySlotIndex: 0,
                relicStatBonuses: bonuses);
            var party = new PartyBattleState(new[] { source });

            HealingResult healing = HealingCalculator.Calculate(
                HealingContextFactory.Build(
                    new HealingContextBuildRequest(
                        source,
                        party,
                        0.10d,
                        false,
                        0)));
            ShieldGenerationResult shield =
                ShieldGenerationCalculator.Calculate(
                    ShieldGenerationContextFactory.Build(
                        new ShieldGenerationContextBuildRequest(
                            source,
                            party,
                            0.10d,
                            false,
                            0)));
            double expectedRaw = build.MaxHp * 0.10d * 1.18d;

            Assert.That(source.MaxHp, Is.EqualTo(build.MaxHp));
            Assert.That(healing.SourceMaxHp, Is.EqualTo(build.MaxHp));
            Assert.That(shield.SourceMaxHp, Is.EqualTo(build.MaxHp));
            Assert.That(healing.RawHealing,
                Is.EqualTo(expectedRaw).Within(1e-9d));
            Assert.That(shield.RawShieldAmount,
                Is.EqualTo(expectedRaw).Within(1e-9d));
            Assert.That(healing.FinalHealing,
                Is.EqualTo((long)Math.Floor(expectedRaw)));
            Assert.That(shield.FinalShieldAmount,
                Is.EqualTo((long)Math.Floor(expectedRaw)));
        }

        private static DefinitionDatabase LoadDatabase()
        {
            DefinitionDatabase database =
                AssetDatabase.LoadAssetAtPath<DefinitionDatabase>(
                    DatabasePath);
            Assert.That(database, Is.Not.Null);
            database.Initialize();
            return database;
        }

        private static LocalizationService LoadLocalization()
        {
            LocalizationCatalog catalog =
                AssetDatabase.LoadAssetAtPath<LocalizationCatalog>(
                    LocalizationCatalogPath);
            Assert.That(catalog, Is.Not.Null);
            return catalog.CreateService();
        }

        private static string FormatDescription(
            LocalizationService localization,
            RelicDefinition relic,
            int awakening)
        {
            var values = relic.GetDescriptionValues(awakening)
                .ToDictionary(
                    pair => pair.Key,
                    pair => (object)(pair.Value * 100d).ToString(
                        "0.##",
                        CultureInfo.InvariantCulture));
            return localization.Format(relic.DescriptionKey, values);
        }

        private static RelicInstanceSaveData Instance(
            string instanceId,
            string definitionId,
            int awakening)
        {
            return new RelicInstanceSaveData
            {
                InstanceId = instanceId,
                RelicDefinitionId = definitionId,
                Awakening = awakening
            };
        }

        private static RelicStatBonusSource Source(
            string definitionId,
            RelicEffectType effectType,
            double rate)
        {
            return new RelicStatBonusSource(
                definitionId,
                definitionId + ".name",
                definitionId + ".description",
                effectType,
                5,
                rate);
        }

        private static CharacterBattleState Character(
            string id,
            int slot,
            long maxHp,
            params RelicStatBonusSource[] sources)
        {
            return new CharacterBattleState(
                id,
                slot,
                ElementType.Light,
                maxHp,
                100d,
                permanentRelicEffects: sources);
        }

        private static EffectInstance Effect(
            long runtimeId,
            EffectModifierType modifierType,
            double magnitude)
        {
            return new EffectInstance(
                runtimeId,
                $"effect_{runtimeId}",
                "source",
                EffectCategory.Buff,
                modifierType,
                magnitude,
                2,
                runtimeId);
        }

        private static BossDamageResult Damage(long damage)
        {
            return BossDamageCalculator.Calculate(new BossDamageContext(
                damage,
                0d,
                0d,
                1d,
                0d,
                0d,
                0d,
                0d));
        }
